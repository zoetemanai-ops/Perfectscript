// api/generate-thumbnail.js
// ─────────────────────────────────────────────────────────────────────────────
// Perfect Thumbnail · Vercel Node serverless function (Nano Banana Pro + text layer)
//
// Trigger:  POST { script_run_id }
//   1. Loads the script run, creates a `thumbnail_runs` row (status: pending)
//   2. Responds IMMEDIATELY with the new row id
//   3. Background (waitUntil): Claude art director -> 3 concepts -> Nano Banana Pro
//      renders the SCENE (no text, 1 call/concept) -> we draw the 2 words as a
//      typographic layer with canvas -> upload -> row complete
//
// The 2 words are NOT generated by the image model anymore — they are rendered
// locally (heavy font, outline, accent bar). Pixel-perfect, on-brand, and free.
//
// ── Prerequisites ────────────────────────────────────────────────────────────
//   npm i @anthropic-ai/sdk @google/genai @napi-rs/canvas @supabase/supabase-js @vercel/functions
//
//   Env vars (Vercel, all server-side):
//     ANTHROPIC_API_KEY, GEMINI_API_KEY, SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY
//
//   Storage buckets:
//     creator-photos (PRIVATE) -> creator-photos/<client_slug>/*.jpg  (3-6 per creator)
//     thumbnails     (PUBLIC)  -> finished thumbnails
//
//   maxDuration 300 needs Vercel Pro.
// ─────────────────────────────────────────────────────────────────────────────

import Anthropic from '@anthropic-ai/sdk';
import { GoogleGenAI, Modality } from '@google/genai';
import { createCanvas, loadImage, GlobalFonts } from '@napi-rs/canvas';
import { createClient } from '@supabase/supabase-js';
import { waitUntil } from '@vercel/functions';

export const config = { maxDuration: 300 };

// ── clients ──────────────────────────────────────────────────────────────────
const anthropic = new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY });
const genai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
const supabase = createClient(
  process.env.SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);

// ── config ───────────────────────────────────────────────────────────────────
const ART_DIRECTOR_MODEL = 'claude-opus-4-8';      // the brain
const IMAGE_MODEL = 'gemini-3-pro-image-preview';  // Nano Banana Pro
const REF_BUCKET = 'creator-photos';
const OUT_BUCKET = 'thumbnails';

// text layer
const FONT_URL = 'https://raw.githubusercontent.com/google/fonts/main/ofl/anton/Anton-Regular.ttf';
const FONT_NAME = 'Anton';
const ACCENT_HEX = '#E11D2A';   // bar behind the second word — change to your brand color

